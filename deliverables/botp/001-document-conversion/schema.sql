CREATE DATABASE IF NOT EXISTS matrix_botp
    DEFAULT CHARACTER SET utf8mb4
    DEFAULT COLLATE utf8mb4_unicode_ci;

USE matrix_botp;

CREATE TABLE IF NOT EXISTS matrix_botp_document_type (
    fid BIGINT NOT NULL COMMENT '主键',
    ftenant_id VARCHAR(64) NOT NULL COMMENT '租户ID',
    fsystem_code VARCHAR(64) NOT NULL COMMENT '系统编码',
    fcode VARCHAR(64) NOT NULL COMMENT '单据类型编码',
    fname VARCHAR(128) NOT NULL COMMENT '单据类型名称',
    fservice_code VARCHAR(64) NULL COMMENT '服务编码',
    fadapter_code VARCHAR(128) NOT NULL COMMENT '适配器编码',
    fstatus VARCHAR(32) NOT NULL DEFAULT 'ENABLED' COMMENT '状态',
    fcreate_by BIGINT NULL COMMENT '创建人',
    fcreate_time DATETIME NOT NULL COMMENT '创建时间',
    fmodify_by BIGINT NULL COMMENT '修改人',
    fmodify_time DATETIME NULL COMMENT '修改时间',
    fdelete_flag TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除',
    fversion INT NOT NULL DEFAULT 0 COMMENT '乐观锁版本',
    PRIMARY KEY (fid),
    UNIQUE KEY uk_matrix_botp_document_type (ftenant_id, fsystem_code, fcode, fdelete_flag),
    KEY idx_matrix_botp_document_type_adapter (fadapter_code)
) COMMENT='BOTP单据类型';

CREATE TABLE IF NOT EXISTS matrix_botp_document_field (
    fid BIGINT NOT NULL COMMENT '主键',
    ftenant_id VARCHAR(64) NOT NULL COMMENT '租户ID',
    fdocument_type_id BIGINT NOT NULL COMMENT '单据类型ID',
    fentity_level VARCHAR(32) NOT NULL COMMENT 'HEADER或ENTRY',
    fcode VARCHAR(128) NOT NULL COMMENT '字段编码',
    fname VARCHAR(128) NOT NULL COMMENT '字段名称',
    ffield_type VARCHAR(32) NOT NULL COMMENT '字段类型',
    frequired TINYINT NOT NULL DEFAULT 0 COMMENT '是否必填',
    freadonly TINYINT NOT NULL DEFAULT 0 COMMENT '是否只读',
    fprecision_value INT NULL COMMENT '精度',
    fscale_value INT NULL COMMENT '小数位',
    fmetadata_json JSON NULL COMMENT '扩展元数据',
    fcreate_by BIGINT NULL COMMENT '创建人',
    fcreate_time DATETIME NOT NULL COMMENT '创建时间',
    fmodify_by BIGINT NULL COMMENT '修改人',
    fmodify_time DATETIME NULL COMMENT '修改时间',
    fdelete_flag TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除',
    fversion INT NOT NULL DEFAULT 0 COMMENT '乐观锁版本',
    PRIMARY KEY (fid),
    UNIQUE KEY uk_matrix_botp_document_field (fdocument_type_id, fentity_level, fcode, fdelete_flag),
    KEY idx_matrix_botp_document_field_type (ftenant_id, fdocument_type_id)
) COMMENT='BOTP单据字段元数据';

CREATE TABLE IF NOT EXISTS matrix_botp_conversion_rule (
    fid BIGINT NOT NULL COMMENT '主键',
    ftenant_id VARCHAR(64) NOT NULL COMMENT '租户ID',
    fcode VARCHAR(64) NOT NULL COMMENT '规则编码',
    fname VARCHAR(128) NOT NULL COMMENT '规则名称',
    fsource_system_code VARCHAR(64) NOT NULL COMMENT '源系统编码',
    fsource_document_type VARCHAR(64) NOT NULL COMMENT '源单类型',
    ftarget_system_code VARCHAR(64) NOT NULL COMMENT '目标系统编码',
    ftarget_document_type VARCHAR(64) NOT NULL COMMENT '目标单类型',
    fcurrent_version INT NOT NULL DEFAULT 0 COMMENT '当前版本',
    fstatus VARCHAR(32) NOT NULL DEFAULT 'DRAFT' COMMENT '状态',
    fcreate_by BIGINT NULL COMMENT '创建人',
    fcreate_time DATETIME NOT NULL COMMENT '创建时间',
    fmodify_by BIGINT NULL COMMENT '修改人',
    fmodify_time DATETIME NULL COMMENT '修改时间',
    fdelete_flag TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除',
    fversion INT NOT NULL DEFAULT 0 COMMENT '乐观锁版本',
    PRIMARY KEY (fid),
    UNIQUE KEY uk_matrix_botp_conversion_rule (ftenant_id, fcode, fdelete_flag),
    KEY idx_matrix_botp_conversion_rule_source (ftenant_id, fsource_system_code, fsource_document_type),
    KEY idx_matrix_botp_conversion_rule_target (ftenant_id, ftarget_system_code, ftarget_document_type)
) COMMENT='BOTP转换规则';

CREATE TABLE IF NOT EXISTS matrix_botp_rule_version (
