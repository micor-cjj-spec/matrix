CREATE TABLE IF NOT EXISTS matrix_botp_execution (
    fid BIGINT NOT NULL COMMENT '主键',
    ftenant_id VARCHAR(64) NOT NULL COMMENT '租户ID',
    fexecution_id VARCHAR(64) NOT NULL COMMENT '执行ID',
    fsource_system VARCHAR(64) NOT NULL COMMENT '调用来源系统',
    frequest_id VARCHAR(128) NOT NULL COMMENT '调用方请求号',
