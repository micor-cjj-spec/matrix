CREATE TABLE IF NOT EXISTS matrix_botp_document_relation (
    fid BIGINT NOT NULL COMMENT '主键',
    ftenant_id VARCHAR(64) NOT NULL COMMENT '租户ID',
    fexecution_id VARCHAR(64) NOT NULL COMMENT '执行ID',
    frule_code VARCHAR(64) NOT NULL COMMENT '规则编码',
    frule_version INT NOT NULL COMMENT '规则版本',
    fsource_system_code VARCHAR(64) NOT NULL COMMENT '源系统',
    fsource_document_type VARCHAR(64) NOT NULL COMMENT '源单类型',
    fsource_document_id VARCHAR(128) NOT NULL COMMENT '源单ID',
    ftarget_system_code VARCHAR(64) NOT NULL COMMENT '目标系统',
    ftarget_document_type VARCHAR(64) NOT NULL COMMENT '目标单类型',
    ftarget_document_id VARCHAR(128) NOT NULL COMMENT '目标单ID',
    frelation_status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE' COMMENT '关系状态',
    fcreate_by BIGINT NULL COMMENT '创建人',
    fcreate_time DATETIME NOT NULL COMMENT '创建时间',
    fmodify_by BIGINT NULL COMMENT '修改人',
    fmodify_time DATETIME NULL COMMENT '修改时间',
    fdelete_flag TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除',
