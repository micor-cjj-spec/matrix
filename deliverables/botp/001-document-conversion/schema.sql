    famount DECIMAL(23, 10) NULL COMMENT '关联金额',
    fbase_quantity DECIMAL(23, 10) NULL COMMENT '基本数量',
    fbase_amount DECIMAL(23, 10) NULL COMMENT '本位币金额',
    frelation_status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE' COMMENT '关系状态',
    fcreate_by BIGINT NULL COMMENT '创建人',
    fcreate_time DATETIME NOT NULL COMMENT '创建时间',
    fmodify_by BIGINT NULL COMMENT '修改人',
    fmodify_time DATETIME NULL COMMENT '修改时间',
    fdelete_flag TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除',
    fversion INT NOT NULL DEFAULT 0 COMMENT '乐观锁版本',
    PRIMARY KEY (fid),
    KEY idx_matrix_botp_relation_entry_source (ftenant_id, fsource_entry_id, frelation_status),
    KEY idx_matrix_botp_relation_entry_target (ftenant_id, ftarget_entry_id, frelation_status),
    KEY idx_matrix_botp_relation_entry_relation (frelation_id)
