    KEY idx_matrix_botp_relation_execution (fexecution_id)
) COMMENT='BOTP单据上下游关系';

CREATE TABLE IF NOT EXISTS matrix_botp_document_relation_entry (
    fid BIGINT NOT NULL COMMENT '主键',
    ftenant_id VARCHAR(64) NOT NULL COMMENT '租户ID',
    frelation_id BIGINT NOT NULL COMMENT '单头关系ID',
    fsource_entry_id VARCHAR(128) NOT NULL COMMENT '源分录ID',
    ftarget_entry_id VARCHAR(128) NOT NULL COMMENT '目标分录ID',
